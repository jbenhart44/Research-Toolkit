def build_parser():
    p = argparse.ArgumentParser(prog="guard_hook_run.py", description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--hooks-dir", help="default: $CLAUDE_PROJECT_DIR/.claude/hooks")
    p.add_argument("--settings", help="default: $CLAUDE_PROJECT_DIR/.claude/settings.json")
    sub = p.add_subparsers(dest="cmd", required=True)

    n = sub.add_parser("new", help="scaffold launcher + logic + self-test")
    n.add_argument("--name", required=True)
    n.add_argument("--posture", required=True, choices=("blocking", "advisory"))
    n.add_argument("--tools", required=True,
                   help='comma list, e.g. "Bash" or "Edit,Write,MultiEdit,NotebookEdit"')
    n.add_argument("--decision", default="deny", choices=("deny", "ask"))
    n.add_argument("--rule", default="[GAP: name the rule this guard enforces, "
                                     "with its file and prov tag]")
    n.add_argument("--reason", default="[GAP: what the user sees when this fires, "
                                       "including how to proceed legitimately]")
    n.add_argument("--false-positives", default="[GAP: what this guard will catch "
                                                "that is actually fine, and the workaround]")
    n.set_defaults(fn=cmd_new)

    r = sub.add_parser("register", help="install into settings.json")
    r.add_argument("--name", required=True)
    r.add_argument("--matcher", required=True)
    r.add_argument("--event", choices=("PreToolUse", "PostToolUse", "SessionStart",
                                       "UserPromptSubmit"))
    r.add_argument("--posture", default="blocking", choices=("blocking", "advisory"))
    r.set_defaults(fn=cmd_register)

    f = sub.add_parser("failfirst", help="prove the self-test bites")
    f.add_argument("--name", required=True)
    f.set_defaults(fn=cmd_failfirst)

    a = sub.add_parser("audit", help="sweep existing hooks for known traps")
    a.set_defaults(fn=cmd_audit)
    return p


def main(argv=None):
    args = build_parser().parse_args(argv)
    return args.fn(args)


if __name__ == "__main__":
    sys.exit(main())
