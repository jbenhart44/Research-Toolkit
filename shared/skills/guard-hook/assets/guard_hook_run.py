def fill(template, **kw):
    out = template
    for k, v in kw.items():
        out = out.replace("@@" + k + "@@", v)
    return out


# --------------------------------------------------------------------------
# new -- scaffold the three files
# --------------------------------------------------------------------------

def cmd_new(args):
    name = args.name
    if not NAME_RE.match(name):
        return die(2, "name must be lowercase [a-z][a-z0-9_]*, got %r" % name)

    hd = hooks_dir(args)
    os.makedirs(hd, exist_ok=True)
    targets = {
        "launcher": os.path.join(hd, name + ".sh"),
        "logic": os.path.join(hd, name + ".py"),
        "selftest": os.path.join(hd, name + "_selftest.py"),
    }
    existing = [p for p in targets.values() if os.path.exists(p)]
    if existing:
        return die(2, "COLLISION, nothing written: " + ", ".join(
            os.path.basename(p) for p in existing))

    tools = [t.strip() for t in args.tools.split(",") if t.strip()]
    if not tools:
        return die(2, "--tools must name at least one tool")
    tools_tuple = ", ".join('"%s"' % t for t in tools)
    if len(tools) == 1:
        tools_tuple += ","

    event = "PostToolUse" if args.posture == "advisory" else "PreToolUse"
    body = ADVISORY_PY if args.posture == "advisory" else BLOCKING_PY
    field = "command" if tools[0] == "Bash" else "content"

    common = dict(NAME=name, DATE=datetime.date.today().isoformat(), EVENT=event,
                  TOOLS=tools_tuple, DECISION=args.decision, RULE=args.rule,
                  REASON=args.reason, FALSEPOS=args.false_positives,
                  SENTINEL=UNAUTHORED, POSTURE=args.posture,
                  FIRSTTOOL=tools[0], FIELD=field)

    with open(targets["launcher"], "w") as f:
        f.write(fill(LAUNCHER, **common))
    os.chmod(targets["launcher"], 0o755)
    with open(targets["logic"], "w") as f:
        f.write(fill(body, **common))
    with open(targets["selftest"], "w") as f:
        f.write(fill(SELFTEST_PY, **common))

    print("SCAFFOLDED /%s  posture=%s  event=%s  tools=%s"
          % (name, args.posture, event, ",".join(tools)))
    for k in ("launcher", "logic", "selftest"):
        print("  " + os.path.relpath(targets[k], ROOT))
    print("")
    print("NOT registered, and not registerable yet. Both files carry the")
    print("%s sentinel: author TRIGGER and the case lists, delete the two" % UNAUTHORED)
    print("sentinel lines, then run:")
    print("  guard_hook_run.py failfirst --name %s" % name)
    print("  guard_hook_run.py register  --name %s --matcher '<matcher>'" % name)
    return 0


# --------------------------------------------------------------------------
# register -- backup, insert, validate, roll back on failure
# --------------------------------------------------------------------------

def run_selftest(name, hd):
    st = os.path.join(hd, name + "_selftest.py")
    if not os.path.exists(st):
        return None, "no self-test file at " + st
    r = subprocess.run([sys.executable, st], capture_output=True, text=True, timeout=300)
    return r, None


def cmd_register(args):
    name = args.name
    hd = hooks_dir(args)
    logic = os.path.join(hd, name + ".py")
    st = os.path.join(hd, name + "_selftest.py")
    if not os.path.exists(logic):
        return die(2, "no guard at " + logic + " -- run `new` first")

    for path in (logic, st):
        if os.path.exists(path) and UNAUTHORED in open(path).read():
            return die(3, "refused: %s still carries the %s sentinel. An unauthored "
                          "guard must never be registered as live."
                       % (os.path.basename(path), UNAUTHORED))

    r, err = run_selftest(name, hd)
    if err:
        return die(4, "refused: " + err)
    if r.returncode != 0:
        sys.stderr.write(r.stdout)
        return die(4, "refused: self-test exits %d. Fix the guard, not the test."
                   % r.returncode)

    sp = settings_path(args)
    if not os.path.exists(sp):
        return die(2, "no settings file at " + sp)
    before = open(sp).read()
    try:
        cfg = json.loads(before)
    except ValueError as exc:
        return die(2, "settings.json is not valid JSON before we touched it (%s)" % exc)

    event = args.event or ("PostToolUse" if args.posture == "advisory" else "PreToolUse")
    command = '"$CLAUDE_PROJECT_DIR/.claude/hooks/%s.sh"' % name
    entry = {"matcher": args.matcher,
             "hooks": [{"type": "command", "command": command}]}

    hooks = cfg.setdefault("hooks", {}).setdefault(event, [])
    for e in hooks:
        for h in e.get("hooks", []):
            if h.get("command") == command and e.get("matcher") == args.matcher:
                print("ALREADY REGISTERED  %s / matcher=%s -- no change."
                      % (event, args.matcher))
                return 0

    # TRAP: an `if:` condition matches only commands BEGINNING with the verb, so a
    # chained `git add -A && git push --force` matches no `if: Bash(git push *)`. Register once,
    # unconditionally, and filter inside the Python.
    if args.matcher and any(t in args.matcher for t in ("Edit", "Write")):
        missing = [t for t in WRITE_TOOLS if t not in args.matcher]
        if missing:
            print("WARNING: matcher %r omits %s, and calls to those tools will never "
                  "reach this guard."
                  % (args.matcher, "|".join(missing)), file=sys.stderr)

    stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
    backup = sp + ".bak-" + stamp
    shutil.copy2(sp, backup)

    hooks.append(entry)
    try:
        with open(sp, "w") as f:
            json.dump(cfg, f, indent=2)
            f.write("\n")
        reread = json.loads(open(sp).read())
        found = any(h.get("command") == command
                    for e in reread.get("hooks", {}).get(event, [])
                    for h in e.get("hooks", []))
        if not found:
            raise ValueError("entry absent after write")
    except Exception as exc:
        shutil.copy2(backup, sp)
        return die(5, "write failed (%s) -- settings.json ROLLED BACK from %s"
                   % (exc, os.path.basename(backup)))

    print("REGISTERED  %s  event=%s  matcher=%s" % (name, event, args.matcher))
    print("  backup: " + os.path.relpath(backup, ROOT))
    print("  Test it with one live call before calling it active: a hook added mid-session")
    print("  has been seen both to fire at once and not to fire until the next session.")
    return 0


# --------------------------------------------------------------------------
# failfirst -- neuter the guard and require the self-test to fail
# --------------------------------------------------------------------------

def neuter(source):
    """Replace the TRIGGER assignment with a pattern that matches nothing.
    Returns the mutated source, or None if TRIGGER could not be located."""
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return None
    span = None
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
                isinstance(t, ast.Name) and t.id == "TRIGGER" for t in node.targets):
            span = (node.lineno, node.end_lineno)
    if not span:
        return None
    lines = source.splitlines(keepends=True)
    lines[span[0] - 1:span[1]] = ['TRIGGER = re.compile(r"(?!x)x")  # NEUTERED\n']
    return "".join(lines)


def cmd_failfirst(args):
    name = args.name
    hd = hooks_dir(args)
    logic = os.path.join(hd, name + ".py")
    if not os.path.exists(logic):
        return die(2, "no guard at " + logic)

    original = open(logic).read()
    digest = hashlib.sha256(original.encode()).hexdigest()
    mutant = neuter(original)
    if mutant is None:
        return die(2, "could not locate a module-level TRIGGER assignment in %s -- "
                      "failfirst cannot prove anything about a guard it cannot neuter"
                   % os.path.basename(logic))

    try:
        with open(logic, "w") as f:
            f.write(mutant)
        broken, err = run_selftest(name, hd)
        if err:
            return die(4, err)
    finally:
        with open(logic, "w") as f:
            f.write(original)

    if hashlib.sha256(open(logic).read().encode()).hexdigest() != digest:
        return die(2, "RESTORE FAILED -- %s no longer matches its original checksum"
                   % os.path.basename(logic))

    if broken.returncode == 0:
        sys.stderr.write(broken.stdout)
        return die(6, "the self-test PASSED against a neutered guard. The test does "
                      "not exercise TRIGGER, so its clean run proves nothing. "
                      "Author cases that fail when the pattern is removed.")

    clean, err = run_selftest(name, hd)
    if err:
        return die(4, err)
    if clean.returncode != 0:
        sys.stderr.write(clean.stdout)
        return die(4, "restored guard does not pass its own self-test (exit %d)"
                   % clean.returncode)

    print("FAIL-FIRST PROVEN for %s" % name)
    print("  neutered guard : self-test exit %d (failed, as required)" % broken.returncode)
    print("  restored guard : self-test exit 0, checksum matches original")
    tail = [l for l in clean.stdout.splitlines() if l.startswith("PASS")]
    if tail:
        print("  " + tail[-1])
    return 0


# --------------------------------------------------------------------------
# audit -- sweep existing hooks for the known traps
# --------------------------------------------------------------------------

TRAPS = {
    "grep_o_truncation": "shell payload parsing that truncates at the first quote "
                         "inside the JSON value (it has shipped live in real hooks)",
    "logic_in_bash": "decision logic in .sh with no .py alongside "
                     "(bash launches; Python decides)",
    "no_selftest": "no _selftest.py -- a guard that has never failed has never been tested",
    "no_failopen": ".py hook with no parse-error path: a malformed payload is "
                   "indistinguishable from a clean pass",
    "narrow_write_matcher": "matcher names Edit/Write but omits MultiEdit or "
                            "NotebookEdit, which then bypass the guard entirely",
    "if_gated": "registration behind an `if:` prefix pattern -- a chained command "
                "matches none of them and the hook is never invoked",
}


def cmd_audit(args):
    hd = hooks_dir(args)
    if not os.path.isdir(hd):
        return die(2, "no hooks directory at " + hd)

    families, found = {}, []
    for fn in sorted(os.listdir(hd)):
        path = os.path.join(hd, fn)
        if not os.path.isfile(path) or not (fn.endswith(".sh") or fn.endswith(".py")):
            continue
        stem = fn[:-len("_selftest.py")] if fn.endswith("_selftest.py") \
            else os.path.splitext(fn)[0]
        fam = families.setdefault(stem, {"sh": None, "py": None, "test": False})
        if fn.endswith("_selftest.py"):
            fam["test"] = True
        elif fn.endswith(".sh"):
            fam["sh"] = path
        else:
            fam["py"] = path

    for stem, fam in sorted(families.items()):
        if fam["sh"]:
            text = open(fam["sh"], errors="replace").read()
            # Comments are stripped FIRST. A launcher may document the truncation bug
            # it was rewritten to fix, and matching that prose reports a closed hole. A guard that cannot tell
            # a description from an instruction is the same defect the delete-guard
            # carries knowingly -- here it is cheap to avoid, so avoid it.
            code = [l for l in text.splitlines()
                    if l.strip() and not l.strip().startswith("#")]
            body = "\n".join(code)
            if "grep -o" in body and '"command"' in body:
                found.append(("grep_o_truncation", stem, os.path.basename(fam["sh"])))
            if not fam["py"] and len(code) > 4:
                found.append(("logic_in_bash", stem,
                              "%d code lines, no .py" % len(code)))
        if not fam["test"]:
            found.append(("no_selftest", stem, "-"))
        if fam["py"]:
            text = open(fam["py"], errors="replace").read()
            if "json.load" in text and "except" not in text:
                found.append(("no_failopen", stem, os.path.basename(fam["py"])))

    sp = settings_path(args)
    if os.path.exists(sp):
        try:
            cfg = json.loads(open(sp).read())
        except ValueError as exc:
            return die(2, "settings.json is not valid JSON (%s)" % exc)
        for event, entries in (cfg.get("hooks") or {}).items():
            for e in entries:
                m = e.get("matcher") or ""
                label = ",".join(h.get("command", "?").rsplit("/", 1)[-1].strip('"')
                                 for h in e.get("hooks", []))
                if "if" in e:
                    found.append(("if_gated", label, "%s if=%r" % (event, e["if"])))
                if any(t in m for t in ("Edit", "Write")):
                    missing = [t for t in WRITE_TOOLS if t not in m]
                    if missing:
                        found.append(("narrow_write_matcher", label,
                                      "%s omits %s" % (m, "|".join(missing))))

    print("GUARD_HOOK AUDIT  %s" % os.path.relpath(hd, ROOT))
    print("  %d hook families, %d with a self-test"
          % (len(families), sum(1 for f in families.values() if f["test"])))
    if not found:
        print("  no traps found")
        return 0
    by_trap = {}
    for trap, who, detail in found:
        by_trap.setdefault(trap, []).append((who, detail))
    print("  %d finding(s)\n" % len(found))
    for trap in sorted(by_trap):
        print("%s -- %s" % (trap.upper(), TRAPS[trap]))
        for who, detail in sorted(by_trap[trap]):
            print("  %-32s %s" % (who, detail))
        print("")
    return 7


